def pick(accept_language="", explicit=""):
    code = (explicit or "").strip().lower()[:2]
    if code in LANGS:
        return code
    for part in (accept_language or "").split(","):
        tag = part.split(";")[0].strip().lower()[:2]
        if tag in LANGS:
            return tag
    return "en"


